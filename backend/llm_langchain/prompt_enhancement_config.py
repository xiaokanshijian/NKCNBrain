# ==================== 辅助函数 ====================

def get_enhanced_prompt(original_prompt, prompt_type):
    """
    获取增强后的prompt

    Args:
        original_prompt: 原始prompt
        prompt_type: "summary", "summary_multi_incremental", "topic", "topic_question"

    Returns:
        增强后的prompt
    """
    if ENHANCEMENT_MODE == "full":
        # 完全替换模式（暂不实现，保留接口）
        from llm_langchain.enhanced_prompts import (
            get_enhanced_summary_prompt,
            get_enhanced_topic_prompt,
            get_enhanced_topic_question_prompt
        )

        if prompt_type in ("summary", "summary_multi_incremental"):
            return get_enhanced_summary_prompt()
        elif prompt_type == "topic":
            return get_enhanced_topic_prompt()
        elif prompt_type == "topic_question":
            return get_enhanced_topic_question_prompt()

    elif ENHANCEMENT_MODE == "append":
        # 追加模式（推荐）
        if prompt_type == "summary_multi_incremental" and ENABLE_ENHANCED_SUMMARY:
            return original_prompt + MULTI_INCREMENTAL_SUMMARY_SUFFIX
        if prompt_type == "summary" and ENABLE_ENHANCED_SUMMARY:
            return original_prompt + SUMMARY_ENHANCEMENT_SUFFIX
        elif prompt_type == "topic" and ENABLE_ENHANCED_TOPIC:
            return original_prompt + TOPIC_ENHANCEMENT_SUFFIX
        elif prompt_type == "topic_question" and ENABLE_ENHANCED_TOPIC_QUESTION:
            return original_prompt + TOPIC_QUESTION_ENHANCEMENT_SUFFIX
    
    # 默认返回原prompt
    return original_prompt


def is_enhancement_enabled(prompt_type):
    """
    检查某个类型的prompt是否启用增强
    
    Args:
        prompt_type: "summary", "topic", "topic_question"
        
    Returns:
        bool: 是否启用增强
    """
    if prompt_type == "summary":
        return ENABLE_ENHANCED_SUMMARY
    elif prompt_type == "topic":
        return ENABLE_ENHANCED_TOPIC
    elif prompt_type == "topic_question":
        return ENABLE_ENHANCED_TOPIC_QUESTION
    return False

