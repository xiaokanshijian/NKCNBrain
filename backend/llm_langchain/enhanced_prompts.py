def enhance_original_prompt(original_prompt, enhancement_type="summary"):
    """
    增强原有prompt（如果不想完全替换，可以用这个函数增强）
    
    Args:
        original_prompt: 原始prompt
        enhancement_type: "summary", "topic", "topic_question"
        
    Returns:
        增强后的prompt
    """
    if enhancement_type == "summary":
        enhancement = """
        
【认知增强要求】
在完成上述摘要的基础上，进一步挖掘：
1. 文档的隐含假设和思维框架
2. 跨段落的潜在联系
3. 意外但合理的洞察
4. 可操作的实践建议
5. 用户可能忽视的重要维度

让摘要从"信息提取"升级为"认知增强"。
"""
