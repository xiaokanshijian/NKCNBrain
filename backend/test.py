import re


def extract_number_SFT(text):
    # 使用正则表达式匹配 'xxxxx分yyyy' 中的 'xxxxx'
    match = re.search(r'(\d+(?:\.\d+)?)_', text)
    if match:
        # 从匹配结果中提取数字，并转换为浮点数
        number = float(match.group(1))
        return number
    else:
        # 如果没有匹配到，返回None
        return None
    

